const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');

module.exports = async (page, original) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Open wall', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const wallSelect = dialog.getByRole('combobox', { name: 'Selected wall', exact: true });
  await wallSelect.selectOption('south');
  await dialog.getByLabel('Wall measurement units').selectOption('m');
  const layers = dialog.getByRole('region', { name: 'Design layers', exact: true });
  const count = () => layers.getByRole('button').count();
  const near = (actual, expected) => assert.ok(Math.abs(Number(actual) - expected) < 0.015, `${actual} != ${expected}`);
  const field = label => dialog.getByRole('spinbutton', { name: label, exact: true });
  const editNumber = async (label, value) => { await field(label).fill(String(value)); await field(label).press('Enter'); };
  const point = (u, v) => dialog.locator('.wall-elevation > g').evaluate((group, { u, v }) => {
    const scale = Math.min(790 / 6, 440 / 3);
    const x = (1000 - 6 * scale) / 2 + u * scale;
    const y = (650 - 3 * scale) / 2 + (3 - v) * scale;
    const point = new DOMPoint(x, y).matrixTransform(group.getScreenCTM());
    return { x: point.x, y: point.y };
  }, { u, v });
  const drag = async (from, to) => {
    await page.mouse.move(from.x, from.y); await page.mouse.down();
    await page.mouse.move(to.x, to.y, { steps: 8 }); await page.mouse.up();
  };
  await dialog.getByRole('button', { name: 'Draw paint', exact: true }).click();
  await drag(await point(0.6, 0.5), await point(1.8, 1.4));
  assert.equal(await count(), 1);
  near(await field('Item width').inputValue(), 1.2);
  near(await field('Item height').inputValue(), 0.9);
  await dialog.getByRole('textbox', { name: 'Item name', exact: true }).fill('Accent block');
  await field('Item width').focus();
  await dialog.getByLabel('Item color', { exact: true }).fill('#c59173');
  await drag(await point(1.2, 0.95), await point(2.2, 1.15));
  near(await field('Left · U').inputValue(), 1.6);
  near(await field('Bottom · V').inputValue(), 0.7);
  await dialog.getByRole('button', { name: 'Undo wall edit' }).click();
  near(await field('Left · U').inputValue(), 0.6);
  await dialog.getByRole('button', { name: 'Redo wall edit' }).click();
  near(await field('Left · U').inputValue(), 1.6);
  const handle = await dialog.locator('[data-resize-item]').boundingBox();
  await drag({ x: handle.x + handle.width / 2, y: handle.y + handle.height / 2 }, await point(3, 1.8));
  near(await field('Item width').inputValue(), 1.4);
  near(await field('Item height').inputValue(), 1.1);
  await editNumber('Item width', 99);
  assert.match(await dialog.getByRole('alert').innerText(), /past the wall/);
  near(await field('Item width').inputValue(), 1.4);
  await editNumber('Item rotation', 15);
  assert.equal(await dialog.getByRole('alert').count(), 0);
  await dialog.getByLabel('Wall color', { exact: true }).fill('#e8dfd1');
  await dialog.getByRole('button', { name: 'Exterior', exact: true }).click();
  assert.equal(await dialog.getByLabel('Wall color', { exact: true }).inputValue(), '#aabbcc');
  await dialog.getByRole('button', { name: 'Interior', exact: true }).click();
  assert.equal(await dialog.getByLabel('Wall color', { exact: true }).inputValue(), '#e8dfd1');
  for (const kind of ['wall art', 'mirror', 'shelf', 'wall panel']) {
    await dialog.getByRole('button', { name: `Add ${kind}`, exact: true }).click();
  }
  await editNumber('Left · U', 3.8);
  assert.equal(await count(), 5);
  await dialog.getByRole('button', { name: 'Duplicate item', exact: true }).click();
  assert.equal(await count(), 6);
  await dialog.getByRole('button', { name: 'Delete item', exact: true }).click();
  assert.equal(await count(), 5);
  await dialog.getByRole('button', { name: 'Undo wall edit' }).click();
  assert.equal(await count(), 6);
  await dialog.getByRole('button', { name: 'Redo wall edit' }).click();
  assert.equal(await count(), 5);
  await layers.getByRole('button', { name: /Wall panel/ }).click();
  await dialog.getByRole('button', { name: 'Send backward' }).click();
  assert.match(await layers.getByRole('button').first().innerText(), /Shelf/);
  await dialog.getByRole('button', { name: '3D preview', exact: true }).click();
  const canvas = dialog.locator('.wall-isolation canvas');
  await canvas.waitFor();
  await canvas.evaluate(element => { element.dataset.retained = 'design-preview'; });
  await dialog.getByLabel('Item color', { exact: true }).fill('#c2aa88');
  assert.equal(await canvas.getAttribute('data-retained'), 'design-preview', '3D edits retain renderer and camera');
  assert.equal(await dialog.locator('.wall-webgl-error').count(), 0);
  await dialog.locator('.wall-inspector').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: path.join(os.tmpdir(), 'house3d-wall-design-3d.png') });
  await dialog.getByRole('button', { name: '2D elevation', exact: true }).click();
  await page.screenshot({ path: path.join(os.tmpdir(), 'house3d-wall-design-2d.png') });
  await dialog.getByText('Copy design to another wall', { exact: true }).click();
  await dialog.getByRole('combobox', { name: 'Destination wall', exact: true }).selectOption('north');
  assert.equal(await dialog.getByRole('button', { name: 'Copy wall design' }).isDisabled(), true, 'Copy rejects target openings');
  await dialog.getByRole('combobox', { name: 'Destination room', exact: true }).selectOption('custom-room');
  await dialog.getByRole('combobox', { name: 'Destination wall', exact: true }).selectOption('wall-2');
  await dialog.getByRole('combobox', { name: 'Destination surface', exact: true }).selectOption('Exterior');
  await dialog.getByRole('combobox', { name: 'Copy sizing', exact: true }).selectOption('Scale to fit');
  await dialog.getByRole('button', { name: 'Copy wall design' }).click();
  assert.match(await dialog.getByRole('status').last().innerText(), /copied/);
  await dialog.getByLabel("Wall's room").selectOption('custom-room');
  await wallSelect.selectOption('wall-2');
  await dialog.getByRole('button', { name: 'Exterior', exact: true }).click();
  assert.equal(await count(), 5);
  await dialog.getByRole('button', { name: 'Undo wall edit' }).click();
  assert.equal(await count(), 0, 'Copy is one undo step');
  await dialog.getByRole('button', { name: 'Redo wall edit' }).click();
  assert.equal(await count(), 5);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1), true);
  await dialog.getByRole('button', { name: 'Save design', exact: true }).click();
  await dialog.getByText('Project saved.', { exact: true }).waitFor();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('room-paint-studio.projects.v1'))[0]);
  for (const [i, room] of saved.rooms.entries()) {
    assert.deepEqual(room.dimensions, original.rooms[i].dimensions);
    assert.deepEqual(room.openings, original.rooms[i].openings);
    assert.deepEqual(room.furniture, original.rooms[i].furniture);
  }
  const source = saved.rooms[0].wallDesigns.find(d => d.wall === 'south' && d.surface === 'Interior');
  const copy = saved.rooms[1].wallDesigns.find(d => d.wall === 'wall-2' && d.surface === 'Exterior');
  assert.equal(source.items.length, 5); assert.equal(copy.items.length, 5);
  assert.ok(copy.items.every(item => !source.items.some(original => original.id === item.id)));
  near(copy.items[0].width / source.items[0].width, 0.5);
  await page.reload();
  await page.getByRole('heading', { name: 'Test room', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Open wall', exact: true }).click();
  await page.getByRole('dialog').getByRole('combobox', { name: 'Selected wall', exact: true }).selectOption('south');
  assert.equal(await page.getByRole('region', { name: 'Design layers', exact: true }).getByRole('button').count(), 5, 'Design survives reload');
  console.log('Design checks passed; screenshots: /tmp/house3d-wall-design-{2d,3d}.png');
};
